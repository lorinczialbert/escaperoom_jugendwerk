#!/usr/bin/env python3
"""Converts the Google-Sheets HTML export into data/schedule.js.

Run again whenever the Tagesplan sheet changes:
    python3 tools/convert-sheet.py path/to/Tagesplan.html
"""
import sys, re, json
from bs4 import BeautifulSoup

SRC = sys.argv[1] if len(sys.argv) > 1 else 'Tagesplan.html'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'data/schedule.js'

FIRST_ROW, LAST_ROW = 1, 39      # sheet grid rows we care about
TIME_COL = 1                      # column A
DAY_COLS = [3, 4, 5, 6, 7, 8, 9]  # B..H  (col 2 is hidden/zero-width)

# (row, col) -> item id.  This is the ONLY hand-maintained mapping.
ITEM_CELLS = {
    'anmeldung':      [(18, 3), (19, 3)],
    'bibelarbeit':    [(14, 4), (14, 5), (14, 6), (11, 7), (14, 8)],
    'ma_besprechung': [(39, c) for c in range(3, 9)],
    'singen':         [(13, 4), (13, 6), (13, 8)],
    'wasserspiele':   [(19, 8), (20, 8)],
    'gelaendespiel':  [(19, 4), (20, 4)],
    'wanderung':      [(2, 5), (9, 5), (10, 5), (11, 5), (16, 5)],
    'essen':          [(8, c) for c in range(4, 10)]
                      + [(16, 4), (16, 6), (16, 7), (16, 8)]
                      + [(25, c) for c in range(3, 9)],
    'stockbrot':      [(28, 5)],
    'lagerfeuer':     [(27, 5), (29, 8), (30, 8)],
}
CELL_ITEM = {rc: item for item, cells in ITEM_CELLS.items() for rc in cells}


def parse_styles(css):
    out = {}
    for m in re.finditer(r'\.ritz \.waffle \.(s\d+)\{([^}]*)\}', css):
        d = dict(p.split(':', 1) for p in m.group(2).split(';') if ':' in p)
        out[m.group(1)] = {
            'bg': d.get('background-color', '#ffffff'),
            'align': d.get('text-align', 'left')[0],
            'bold': d.get('font-weight') == 'bold',
            'italic': d.get('font-style') == 'italic',
            'size': int(re.sub(r'\D', '', d.get('font-size', '10pt')) or 10),
            'br': 2 if '2px' in d.get('border-right', '') else 1,
            'bb': 2 if '2px' in d.get('border-bottom', '') else 1,
        }
    return out


def main():
    soup = BeautifulSoup(open(SRC, encoding='utf-8').read(), 'html.parser')
    styles = parse_styles(soup.find('style').string)
    trs = soup.find('table').find_all('tr')

    heights, cells, occupied = {}, [], set()
    for ri, tr in enumerate(trs):
        m = re.search(r'height:\s*(\d+)px', tr.get('style') or '')
        heights[ri] = int(m.group(1)) if m else 17
        ci = 0
        for td in tr.find_all(['td', 'th']):
            while (ri, ci) in occupied:
                ci += 1
            rs = int(td.get('rowspan', 1))
            for a in range(rs):
                occupied.add((ri + a, ci))
            if FIRST_ROW <= ri <= LAST_ROW and ci in [TIME_COL] + DAY_COLS:
                st = styles.get(' '.join(td.get('class', [])), {})
                cell = {
                    'r': ri,
                    'c': 0 if ci == TIME_COL else DAY_COLS.index(ci) + 1,
                    'rs': rs,
                    'text': td.get_text(' ', strip=True),
                    'bg': st.get('bg', '#ffffff'),
                    'align': st.get('align', 'l'),
                    'bold': st.get('bold', False),
                    'italic': st.get('italic', False),
                    'br': st.get('br', 1),
                    'bb': st.get('bb', 1),
                }
                if (ri, ci) in CELL_ITEM:
                    cell['item'] = CELL_ITEM[(ri, ci)]
                cells.append(cell)
            ci += 1

    tagged = {c['item'] for c in cells if 'item' in c}
    missing = set(ITEM_CELLS) - tagged
    if missing:
        print('WARNING: no cells matched for', missing)

    data = {
        'rows': [{'r': r, 'h': heights[r]} for r in range(FIRST_ROW, LAST_ROW + 1)],
        'cells': cells,
        'timeColWidth': 78,
        'dayColWidth': 168,
    }
    js = ('// GENERATED by tools/convert-sheet.py - do not edit by hand.\n'
          'const SCHEDULE = ' + json.dumps(data, ensure_ascii=False, indent=0) + ';\n'
          "if (typeof module !== 'undefined') module.exports = SCHEDULE;\n"
          "else window.SCHEDULE = SCHEDULE;\n")
    open(OUT, 'w', encoding='utf-8').write(js)
    print(f'wrote {OUT}: {len(cells)} cells, {len(tagged)} items tagged')


main()
